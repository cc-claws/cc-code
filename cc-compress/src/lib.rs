//! CLI 输出压缩过滤器：在执行命令得到的原始输出之上，剥离噪音、折叠重复、
//! 按命令语义保留关键行，减少进入模型上下文的 token。
//!
//! # 设计约定
//!
//! - **纯函数库**：只做字符串进、字符串出，不 spawn 进程、不读环境、不碰文件系统。
//!   需要外部信息的过滤器由调用方（`cc-tools`）在调用前完成。
//! - **永不反向膨胀**：所有过滤器出口都应经过 [`guard::never_worse`]，
//!   过滤结果比原文更费 token 时回退原文。
//! - **按字符而非字节截断**：CJK 按字节切会产生非法 UTF-8，
//!   行截断统一走字符级操作。
//!
//! # 模块
//!
//! - [`ansi`]：ANSI 转义剥离与 `\r` 覆盖（进度条）规范化
//! - [`guard`]：token 估算与「不得变差」守卫
//! - [`dedup`]：相邻重复行折叠

pub mod ansi;
pub mod dedup;
pub mod guard;

